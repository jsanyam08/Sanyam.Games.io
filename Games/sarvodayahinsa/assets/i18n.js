  const LANGS = ['en', 'hi'];
  let lang = 'en';
  try {
    const s = localStorage.getItem('sa.lang');
    if (LANGS.includes(s)) lang = s;
  } catch (e) {}

  const listeners = new Set();

  /* t('key', {x: 5}) — a missing key returns the key itself, so a gap
     is obvious on screen instead of rendering as blank. */
  function t(key, vars) {
    const row = D[key];
    let s = row ? (row[lang === 'hi' ? 1 : 0] || row[0]) : key;
    if (vars) Object.keys(vars).forEach(k => { s = s.split('{' + k + '}').join(vars[k]); });
    return s;
  }

  function set(l) {
    if (!LANGS.includes(l) || l === lang) return;
    lang = l;
    try { localStorage.setItem('sa.lang', l); } catch (e) {}
    document.documentElement.lang = l;
    document.dispatchEvent(new CustomEvent('sa:lang', { detail: { lang: l } }));
    listeners.forEach(cb => cb(l));
  }

  const toggle = () => set(lang === 'en' ? 'hi' : 'en');
  const onChange = cb => { listeners.add(cb); return () => listeners.delete(cb); };

  document.documentElement.lang = lang;

  return { t, set, toggle, onChange, LANGS, get lang() { return lang; } };
